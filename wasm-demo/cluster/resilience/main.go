func streamingReplication() {
	fmt.Println("── 3. SYNC vs ASYNC REPLICATION ──")
	fmt.Println()
	fmt.Println("  Async replication (the PostgreSQL default):")
	fmt.Println("    Primary commits → returns to client → sends WAL to replica.")
	fmt.Println("    If the primary crashes between steps 2 and 3, the committed")
	fmt.Println("    transaction is LOST. The replica never saw it. The client")
	fmt.Println("    was told 'success' but the data is gone.")
	fmt.Println()
	fmt.Println("    ┌──────────┐    ① COMMIT         ┌──────────┐")
	fmt.Println("    │  Worker  │ ──────────────────→ │  Primary │")
	fmt.Println("    │ (client) │ ←──── ② OK ─────── │          │")
	fmt.Println("    └──────────┘                     │          │")
	fmt.Println("                                     │ ③ WAL → │ ──→ Replica (maybe)")
	fmt.Println("                                     └──────────┘")
	fmt.Println("                               💥 CRASH HERE = LOST DATA")
	fmt.Println()
	fmt.Println("  For durable workflows, this is UNACCEPTABLE. A worker writes")
	fmt.Println("  payments.Charge result → gets OK → primary crashes → charge")
	fmt.Println("  result is lost → on resume, the workflow either double-charges")
	fmt.Println("  or hits a replay divergence.")
	fmt.Println()
	fmt.Println("  Synchronous replication fixes this:")
	fmt.Println()
	fmt.Println("    ┌──────────┐    ① COMMIT         ┌──────────┐    ② WAL      ┌──────────┐")
	fmt.Println("    │  Worker  │ ──────────────────→ │  Primary │ ────────────→ │  Standby │")
	fmt.Println("    │          │ ←──── ④ OK ─────── │          │ ←── ③ ACK ── │          │")
	fmt.Println("    └──────────┘                     └──────────┘               └──────────┘")
	fmt.Println()
	fmt.Println("  The commit doesn't return to the client until the standby has")
	fmt.Println("  written the WAL to disk. Primary crash → standby has all data.")
	fmt.Println()
	fmt.Println("  The tradeoff: synchronous = higher commit latency. For durable")
	fmt.Println("  workflows, each durable_call is an INSERT into event_history.")
	fmt.Println("  The sync replication latency adds ~1-5ms to each call (network")
	fmt.Println("  RTT to the standby). Since durable_calls are already ~10-100ms")
	fmt.Println("  (real HTTP calls), this overhead is negligible.")
	fmt.Println()
	fmt.Println("  Configuration:")
	fmt.Println()
	fmt.Println("    -- On primary:")
	fmt.Println("    synchronous_commit = remote_write   -- wait for standby disk write")
	fmt.Println("    synchronous_standby_names = 'standby1'")
	fmt.Println()
	fmt.Println("    -- On standby:")
	fmt.Println("    primary_conninfo = 'host=primary port=5432 ...'")
	fmt.Println()
}

func patroniAutoFailover() {
	fmt.Println("── 4. AUTOMATIC FAILOVER WITH PATRONI ──")
	fmt.Println()
	fmt.Println("  Manual failover (SSH in, run pg_ctl promote) means:")
	fmt.Println("    • Mean Time To Recovery (MTTR) = human response time = 5-30 min")
	fmt.Println("    • During those 30 minutes, ALL workflows are stuck")
	fmt.Println("    • Workers can't heartbeat → workflows get reassigned by timeout")
	fmt.Println("    • But... event_history writes fail → workers crash or hang")
	fmt.Println()
	fmt.Println("  Patroni automates this. It's the standard tool for PostgreSQL HA:")
	fmt.Println()
	fmt.Println("  ┌──────────────────────────────────────────────────────────────┐")
	fmt.Println("  │                      ETCD / CONSUL (3 nodes)                 │")
	fmt.Println("  │  Distributed consensus: which PG node is the primary?        │")
	fmt.Println("  └────┬─────────────────────┬─────────────────────┬────────────┘")
	fmt.Println("       │                     │                     │")
	fmt.Println("       ▼                     ▼                     ▼")
	fmt.Println("  ┌──────────┐         ┌──────────┐         ┌──────────┐")
	fmt.Println("  │ Patroni  │         │ Patroni  │         │ Patroni  │")
	fmt.Println("  │  + PG    │         │  + PG    │         │  + PG    │")
	fmt.Println("  │ PRIMARY  │ ──sync──│ STANDBY  │ ──async─│ STANDBY  │")
	fmt.Println("  │ (AZ-a)   │         │ (AZ-b)   │         │ (AZ-c)   │")
	fmt.Println("  └──────────┘         └──────────┘         └──────────┘")
	fmt.Println()
	fmt.Println("  What happens when the primary dies:")
	fmt.Println("    1. Patroni on primary stops sending leader-keepalive to etcd")
	fmt.Println("    2. After ttl (30s), etcd considers the leader slot vacant")
	fmt.Println("    3. Patroni on SYNC standby acquires the leader lock in etcd")
	fmt.Println("    4. Patroni promotes standby to primary (pg_ctl promote)")
	fmt.Println("    5. Patroni reconfigures the async standby to replicate from")
	fmt.Println("       the new primary")
	fmt.Println("    6. Client connections break → workers reconnect → continue")
	fmt.Println()
	fmt.Println("  MTTR: ~30-60 seconds. No human intervention.")
	fmt.Println()
	fmt.Println("  CRITICAL: etcd itself must be 3 nodes (separate VMs), or managed")
	fmt.Println("  etcd (AWS, GCP, or something like etcd-operator on Kubernetes).")
	fmt.Println("  Patroni without reliable etcd can't do safe failover.")
	fmt.Println()
}

func walArchivingPitr() {
	fmt.Println("── 5. WAL ARCHIVING & POINT-IN-TIME RECOVERY ──")
	fmt.Println()
	fmt.Println("  Replication protects against hardware failure. It does NOT")
	fmt.Println("  protect against:")
	fmt.Println("    • Operator runs DROP TABLE event_history; (replicates instantly!)")
	fmt.Println("    • Application bug corrupts data (wrong step numbers, bad JSON)")
	fmt.Println("    • Storage corruption (bit rot in the data files)")
	fmt.Println()
	fmt.Println("  For these, you need WAL archiving + PITR:")
	fmt.Println()
	fmt.Println("  ┌──────────────────────────────────────────────────────────────┐")
	fmt.Println("  │  WAL Archiving to S3 (via wal-g or pgBackRest)               │")
	fmt.Println("  │                                                              │")
	fmt.Println("  │  Continuous: every WAL segment (16MB) pushed to S3           │")
	fmt.Println("  │  as soon as it's full.                                       │")
	fmt.Println("  │                                                              │")
	fmt.Println("  │  Combined with a weekly base backup, you can restore to      │")
	fmt.Println("  │  ANY point in time within the retention window.              │")
	fmt.Println("  └──────────────────────────────────────────────────────────────┘")
	fmt.Println()
	fmt.Println("  Recovery procedure (after DROP TABLE disaster):")
	fmt.Println("    $ wal-g backup-fetch /restore/pg LATEST                    ")
	fmt.Println("    # Add recovery.conf:                                        ")
	fmt.Println("    restore_command = 'wal-g wal-fetch %f %p'                  ")
	fmt.Println("    recovery_target_time = '2026-05-04 14:31:52 UTC'           ")
	fmt.Println("    # (the timestamp JUST before the DROP TABLE)               ")
	fmt.Println("    $ pg_ctl start                                              ")
	fmt.Println()
	fmt.Println("  The WAL-G approach gives you:")
	fmt.Println("    • RPO: ~1 WAL segment (16MB, typically 1-5 minutes of data)")
	fmt.Println("    • RTO: ~time to download base backup + replay WAL")
	fmt.Println("      (for a 100GB database, ~15-30 minutes)")
	fmt.Println("    • Protection against operator error ✅")
	fmt.Println("    • Protection against corruption ✅")
	fmt.Println("    • Protection against region failure ✅")
	fmt.Println("      (S3 is cross-AZ, WAL is continuously archived)")
	fmt.Println()
}

func operatorSafety() {
	fmt.Println("── 6. OPERATOR SAFETY (defense in depth) ──")
	fmt.Println()
	fmt.Println("  Most data loss is caused by humans, not machines. Layers:")
	fmt.Println()
	fmt.Println("  Layer 1 — Application-level protection:")
	fmt.Println("  ┌─────────────────────────────────────────────────────────────┐")
	fmt.Println("  │  • Never issue DROP/TRUNCATE from application code          │")
	fmt.Println("  │  • event_history has no UPDATE/DELETE paths in application  │")
	fmt.Println("  │  • All writes are INSERT (append-only by design!)           │")
	fmt.Println("  │  • Use a restricted DB user for the worker pool:            │")
	fmt.Println("  │    GRANT INSERT ON event_history TO worker_app;             │")
	fmt.Println("  │    GRANT UPDATE (status, heartbeat_at) ON                   │")
	fmt.Println("  │      workflow_instances TO worker_app;                      │")
	fmt.Println("  │    -- worker_app has NO DROP, TRUNCATE, DELETE permissions  │")
	fmt.Println("  └─────────────────────────────────────────────────────────────┘")
	fmt.Println()
	fmt.Println("  Layer 2 — Database-level guardrails:")
	fmt.Println("  ┌─────────────────────────────────────────────────────────────┐")
	fmt.Println("  │  • event_streaming_a_workflow:                              │")
	fmt.Println("  │    statement_timeout = '30s'  (global)                      │")
	fmt.Println("  │    idle_in_transaction_session_timeout = '60s'              │")
	fmt.Println("  │  • Disable autovacuum on event_history (append-only,        │")
	fmt.Println("  │    no updates/deletes, vacuum has nothing to clean)         │")
	fmt.Println("  │  • Consider: ALTER TABLE event_history SET (               │")
	fmt.Println("  │      autovacuum_enabled = false);                           │")
	fmt.Println("  └─────────────────────────────────────────────────────────────┘")
	fmt.Println()
	fmt.Println("  Layer 3 — Human guardrails:")
	fmt.Println("  ┌─────────────────────────────────────────────────────────────┐")
	fmt.Println("  │  • Production DB access via jump host ONLY                   │")
	fmt.Println("  │  • psql session wraps BEGIN; ... COMMIT; (no auto-commit)   │")
	fmt.Println("  │  • .psqlrc sets: \\set ON_ERROR_STOP on                     │")
	fmt.Println("  │  • Prefer flyway/migrate for schema changes, not manual SQL │")
	fmt.Println("  │  • Read-only replicas for ad-hoc queries (never the primary)│")
	fmt.Println("  └─────────────────────────────────────────────────────────────┘")
	fmt.Println()
}

