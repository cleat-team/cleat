// Analysis: making PostgreSQL the rock-solid source of truth for durable workflows.
//
// In this system, PostgreSQL stores the event history that IS the workflow's
// memory. Every durable_call records its result. On replay, the cached results
// are replayed in order. If the database is lost:
//
//   - A workflow that already charged a credit card has no record of it
//   - On resume, it will re-execute the charge (double charge) or fail
//   - The compensation chain is broken (refund relies on having the charge_id)
//
// The database is not optional. It must survive:
//   - Disk failure
//   - Machine failure
//   - Availability zone failure
//   - Operator error (accidental DROP TABLE)
//   - Corruption (bit rot, bad controller, PostgreSQL bug)
//
// Build it into the binary:
//   GOTOOLCHAIN=local /home/rcownie/go/bin/go build -o /tmp/pg_resilience ./cluster/postgres_resilience.go
//   /tmp/pg_resilience

