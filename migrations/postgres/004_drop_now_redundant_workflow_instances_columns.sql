-- cleat#3245 Phase 3 step 4 (cleat#3360): drop the workflow_instances
-- columns that steps 2-3 made redundant and that nothing on workflow_instances
-- itself reads or writes self-referentially any more.
--
-- Scope, and why it is five columns and not "every column steps 2-3
-- mirrored": most mirrored columns still have a LIVE reader on
-- workflow_instances -- the primary write path (StartNewRun, ClaimWorkflows,
-- ReapStaleInstances, FinalizeDeferPhase, ExpireDeferPhases,
-- enforceParentClosePolicy, finalize_workflow_status) still targets
-- workflow_instances first and mirrors onto workflow_leases/workflow_payloads
-- second, and several of those statements read a column's OWN current value
-- to write it back -- `reclaim_count = reclaim_count + 1`,
-- `started_at = COALESCE(started_at, now())`, `SET status =
-- pending_terminal_status`, a RETURNING clause naming `priority`/`trace_id`.
-- A plain `grep -n 'FROM workflow_instances\|JOIN workflow_instances'` does
-- not see any of those -- a bare `UPDATE workflow_instances SET x = x + 1`
-- has neither keyword -- which is exactly how six of the thirteen
-- no-reader-found candidates this survey turned up were actually still read.
-- Re-derive the full enumeration with:
--
--   git ls-files '*.go' | grep -v '_test\.go$' | grep -v '/mysql_\|/mssql_' \
--     | xargs grep -n 'UPDATE workflow_instances\|INSERT INTO workflow_instances\|FROM workflow_instances\|JOIN workflow_instances'
--
-- and read every SET/WHERE/RETURNING clause, not just the FROM/JOIN lines.
--
-- Columns dropped, and why each has no surviving reader:
--
--   cancellation_requested, cancellation_reason
--     CheckCancellation has read workflow_leases exclusively since Phase 3
--     step 3 piece D; RequestCancellation (engine/store_signals.go) wrote
--     workflow_instances AND workflow_leases until this migration's
--     accompanying code change, which left only the workflow_leases write.
--     cleatctl resealpayloads's workflow_instances column spec dropped
--     cancellation_reason too (see cmd/cleatctl/resealpayloads_sensitive_tables.go).
--
--   compacted_at
--     Written by CompactHistory/ClearExpiredCompactionState and never read
--     anywhere -- not even by workflow_payloads, which carries the same
--     column but was never given a mirror write for it either. Unlike the
--     other four, this one was never duplicated onto a mirror table in the
--     first place; it is simply retired.
--
--   plugin_vers
--     No reader and no writer anywhere in the current tree. Confirmed by
--     `git grep -n '\bplugin_vers\b'` returning only this table's own
--     CREATE TABLE line (both workflow_instances and workflow_payloads) and
--     the index-parity test that enumerates every JSONB column from the
--     migration files -- nothing in engine/, cmd/ or plugins/ ever
--     references it.
--
--   concurrency_key (the TEXT column, not its hash)
--     acquireCandidateConcurrencyKey and the claim candidate scan have read
--     workflow_leases exclusively since Phase 3 step 3 piece B. StartNewRun/
--     StartNewRunWithOptions (engine/store_lifecycle.go) wrote it onto both
--     tables until this migration's accompanying code change, which left
--     only insertLeaseAndPayloadRows' workflow_leases write.
--
-- Columns considered and NOT dropped, deferred rather than kept:
--
--   sticky_worker_id, concurrency_key_hash
--     Same reasoning as the two dropped above -- claimStickyWorkflowsOnce
--     and the claim candidate scan have read workflow_leases exclusively
--     since piece B, and nothing on workflow_instances reads either column.
--     They are NOT dropped here because 001_schema.sql indexes each of
--     them (idx_instances_sticky on sticky_worker_id,
--     idx_instances_concurrency_key on concurrency_key_hash), and
--     001_schema.sql is byte-verified against a frozen historical baseline
--     by scripts/verify-postgres-baseline.py (Multi-DB CI), so it cannot be
--     hand-edited to drop those index definitions alongside the columns.
--     PostgreSQL auto-drops an index when its column is dropped, but 001's
--     own CREATE INDEX IF NOT EXISTS statement still names the column, so
--     replaying 001 a second time -- which
--     TestShippedSchema_IsIdempotent does, and which
--     docs/explanation/postgresql-schema.md promises an operator is safe --
--     would fail with "column does not exist" at the moment it tries to
--     recreate that index. Measured directly: dropping sticky_worker_id and
--     concurrency_key_hash here, and only those two, reproduces exactly
--     that failure; the other five columns have no index in 001 and are
--     unaffected, confirmed by dropping only those five and seeing
--     TestShippedSchema_IsIdempotent pass. Deferred to the next baseline
--     regeneration, which will fold the drop into a fresh pg_dump with no
--     such conflict -- track as a follow-up issue rather than forcing it
--     here. concurrency_key itself (dropped above) has no index in 001 and
--     was not affected by this constraint.
--
--   priority, trace_id, pending_terminal_status, started_at, reclaim_count,
--   defer_phase_deadline
--     All six are read by claimWorkflowsOnce/claimStickyWorkflowsOnce's
--     RETURNING clause, or by a self-referential SET/WHERE in
--     ReapStaleInstances, ReapStaleInstancesExcept, FinalizeDeferPhase or
--     ExpireDeferPhases -- every one of them UPDATEs workflow_instances
--     directly, not workflow_leases. (An earlier pass of this survey
--     misclassified all six as unread, by grepping only for FROM/JOIN.)
--
--   status, assigned_to, heartbeat_at, next_wake_at, created_at,
--   generation, def_name, def_version, input, result, error_msg, error_code,
--   error_op, query_state, compaction_state, compaction_step, event_count,
--   history_swept_at, tenant_id, task_queue, continued_from,
--   parent_workflow_id, completed_at, completed_by,
--   signal_seq/signal_seq_at_claim/signal_consumed_seq/
--   signal_consumed_at_claim/promise_seq/promise_seq_at_claim,
--   run_wasm_instance_timeout_ms/run_wasm_wall_clock_ceiling_ms/
--   run_host_retry_budget_ms/run_max_workflow_duration_ms,
--   parent_close_policy
--     Each has a live Postgres reader outside the claim/reap/defer-phase
--     statements above too -- LoadCompactionState, GetChildResult,
--     GetCompactionCandidates, the retention predicates
--     (pgExpiredEventsWorkflows/pgExpiredCompactionState/
--     pgDeadLetteredWorkflows/pgCompletedWorkflows), GetRunLimits,
--     acquireCandidateConcurrencyKey's own liveness check (the issue's named
--     keep item, engine/store_lifecycle.go), childrenClosedByTerminate, or
--     the admin/diagnostic paths in store_admin.go and db.go. parent_close_policy
--     and event_count/history_swept_at are additionally not mirrored to any
--     other table at all, so they could not be dropped even if nothing read
--     them on workflow_instances.
--
-- Falsified, on a scratch database: appending
-- `ALTER TABLE workflow_instances DROP COLUMN IF EXISTS status;` to this
-- file and running `go test ./engine/ -run 'TestClaim|TestAClaim|TestStartNewRun'`
-- against it fails loudly and immediately --
--
--   pq: column "status" of relation "workflow_instances" does not exist at position 2:63 (42703)
--
-- across TestClaimWorkflow, TestClaimWorkflows_Batch, TestClaimStickyWorkflows,
-- TestClaimSkipLocked, TestStartNewRunWithPriority and others, every one
-- failing inside StartNewRun/setupTestData rather than passing regardless of
-- what the migration drops.
-- (TestTheClaimableConcurrencyKeyPredicateIsIdenticalAtEverySite, the
-- issue's own named test, is NOT a case of this: it compares SQL source TEXT
-- across dialects and never opens a database connection, so it stayed green
-- throughout -- confirmed by running it alone against the same mutated
-- migration. A static comparison test is not a substitute for an executed
-- known-positive.)
--
-- IF NOT EXISTS: makes this migration re-runnable against a database that
-- already applied it, the same convention 001-003 use for CREATE. PostgreSQL
-- automatically drops any index that depends solely on a dropped column --
-- no separate DROP INDEX is needed for these five, none of which 001 indexes
-- -- and the fresh-DB build plus TestShippedSchema_IsIdempotent in CI are
-- what verify that holds.
ALTER TABLE workflow_instances DROP COLUMN IF EXISTS cancellation_requested;
ALTER TABLE workflow_instances DROP COLUMN IF EXISTS cancellation_reason;
ALTER TABLE workflow_instances DROP COLUMN IF EXISTS compacted_at;
ALTER TABLE workflow_instances DROP COLUMN IF EXISTS plugin_vers;
ALTER TABLE workflow_instances DROP COLUMN IF EXISTS concurrency_key;
